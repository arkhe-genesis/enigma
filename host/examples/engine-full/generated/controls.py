        # Check if this is a control property
        control_names = ['Purge', 'RunStandby', 'Scram', 'TempCap', 'Throttle']
        if name in control_names:
            # Forward to the control's .value setter
            getattr(self, name).value = value
        else:
            # Normal attribute assignment
            object.__setattr__(self, name, value)

