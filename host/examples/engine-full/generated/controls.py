    def any_switch_activated(self, hardware_only=False):
        """Check if any switch/button went from inactive to active state this frame.
        If hardware_only=True, ignores programmatic control changes."""
        if self.Purge.changed(hardware_only):
            return True
        elif self.RunStandby.changed(hardware_only):
            return True
        elif self.Scram.changed(hardware_only):
            return True
        return False

    def any_switch_deactivated(self, hardware_only=False):
        """Check if any switch/button went from active to inactive state this frame.
        If hardware_only=True, ignores programmatic control changes."""
        return False

    def any_axis_changed(self):
        """Check if any ADC axis value changed this frame"""
        controls = [self.Throttle]
        for control in controls:
            if control.changed():
                return True
        return False

    def any_knob_changed(self):
        """Check if any encoder position changed this frame"""
        controls = [self.TempCap]
        for control in controls:
            if control.changed():
                return True
        return False

    def any_button_pressed(self):
        """Check if any encoder button went from 0 to 1 this frame"""
        controls = [self.TempCap]
        for control in controls:
            # Check if button changed and is now pressed (1)
            if control.button_changed() and control.button == 1:
                return True
        return False

    def any_button_released(self):
        """Check if any encoder button went from 1 to 0 this frame"""
        controls = [self.TempCap]
        for control in controls:
            # Check if button changed and is now released (0)
            if control.button_changed() and control.button == 0:
                return True
        return False


